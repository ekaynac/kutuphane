# --- signals -----------------------------------------------------------------------------------------------
GENERATOR_TOOL = re.compile(  # a NAMED rule-based generator only; generic "this file was generated" proves nothing
    r"(?i)(generated by (typedoc|schemadoc|tools/[\w-]+|sphinx|doxygen|openapi[- ]generator|protoc[\w-]*|buf|"
    r"swagger-codegen|sqlc|jooq|graphql-codegen)|code generated by [\w./-]+.{0,40}do not edit)")
GENERATOR_MODEL = re.compile(
    r"(?i)(generated with \[?claude code|🤖 generated with|co-authored-by: (claude|copilot|codex|gpt|gemini|cursor)|"
    r"(generated|written|drafted|created) (by|with) (an? )?(ai|llm|claude|chatgpt|gpt-?\d|gemini|copilot|"
    r"language model)|hazırlayan: claude|automatically extracted via (local )?llm|llm-assisted|"
    r"ai-usage:\s*ai-(generated|assisted))")
MODEL_LOGIN = re.compile(r"(?i)(copilot|claude|cursor|codex|devin|gemini|openai|chatgpt)")
BOT_LOGIN = re.compile(r"(?i)(\[bot\]$|-bot$|^bot-|^github-actions$|^dependabot)")
REVIEW = re.compile(r"(?im)^\s*(reviewed[- ]by|approved[- ]by|reviewer|onaylayan)\s*[:=]\s*(.+)$")
TRIVIAL_COMMENT = re.compile(r"(?i)^\W*(lgtm|looks good( to me)?|thanks?( you)?|thx|ship it|approved?|merging|"
                             r"\+1|👍|nice|great( work)?|/lgtm|/approve)\W*$")
SPELLING_ONLY = re.compile(r"(?i)(spelling|typo|grammar|formatting)[- ]only|only (fixed )?(spelling|typos|grammar)")
LOG_LINE = re.compile(r"(?m)^(\d{4}-\d\d-\d\d[T ]\d\d:\d\d:\d\d|\w{3} [ \d]\d \d\d:\d\d:\d\d|\S+ - - \[\d\d/\w{3}/\d{4})")
EMAIL = re.compile(r"\b[\w.+-]+@([\w-]+\.)+[a-z]{2,}\b", re.I)
IPV4 = re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b")
PHONE = re.compile(r"(?<!\w)\+\d{1,3}[ \-]?\(?\d{1,4}\)?([ \-]?\d{2,4}){2,4}(?!\w)")
ORCID = re.compile(r"orcid\.org/\d{4}-\d{4}-\d{4}-\d{3}[\dX]")
TCKN = re.compile(r"(?<!\d)[1-9]\d{10}(?!\d)")
NAMED_PERSON = re.compile(r"\b(Mr|Mrs|Ms|Miss|Dr|Prof)\.? [A-Z][a-z]+(?: [A-Z][a-z]+)?|\b(born|died) (on |in )?"
                          r"(\d{1,2} \w+ )?\d{4}\b")
SYNTHETIC_HINT = re.compile(r"(?i)\b(synthetic|fake|dummy|fictitious|fictional|made-up|invented)\b.{0,40}"
                            r"\b(data|record|person|people|customer|name|pii)")
DOC_DOMAINS = re.compile(r"(?i)@(example\.(com|org|net)|[\w.-]+\.(invalid|test|example)|users\.noreply\.github\.com)$")
SPDX_HEADER = re.compile(r"SPDX-License-Identifier:\s*([^\s*]+(?:\s+(?:AND|OR|WITH)\s+[^\s*]+)*)")
CONTENT_USAGE = re.compile(r"(?i)content-usage\s*[:=]\s*\"?([^\"\n>]+)")
TDM = re.compile(r"(?i)tdm-reservation\"?\s*[:=]\s*\"?([01])")
STATUS = re.compile(r"(?im)^\s*(?:[*_#>-]+\s*)?status(?:\*\*)?\s*[:=]\s*\**\s*([A-Za-zÇĞİÖŞÜçğıöşü ]{3,30})")
FRONT = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)
DATE_IN_NAME = re.compile(r"(20\d\d-\d\d-\d\d)")
HOSTILE = [
    (re.compile(r"(?i)base64\s+(-d|--decode)[^\n]*\|\s*(sh|bash)|eval\s*\(\s*atob|exec\(base64"), "decode-and-run"),
    (re.compile(r"(?i)(curl|wget)[^\n|]*\|\s*(sh|bash|source)|source\s*<\(\s*(curl|wget)"), "remote-script"),
    (re.compile(r"(?i)(ignore|disregard|override) (all )?(previous|prior|other|above) (instructions|rules)"), "override"),
    (re.compile(r"[\u200b\u200c\u200d\u2060\ufeff]"), "zero-width-text"),
    (re.compile(r"(?is)<!--[^>]*(agent|assistant|ai)\b[^>]*(send|copy|upload|post|curl)[^>]*-->"), "hidden-comment"),
    (re.compile(r"(?i)(send|post|upload|copy|exfiltrat)\w*[^\n]{0,80}(\.ssh|id_rsa|token|secret|credential|api[_ ]?key|password)"), "exfiltration"),
    (re.compile(r"(?i)(soul|memory)\.md[^\n]{0,60}(append|overwrite|replace|write)|(append|overwrite|write)[^\n]{0,60}(soul|memory)\.md"), "memory-write"),
    (re.compile(r"(?i)never ask for confirmation|approved all actions in advance|do not (tell|mention|show)[^\n]{0,40}(user|this)"), "concealment"),
]
RISKY = [  # powers that are legitimate in many skills but raise the activation risk
    (re.compile(r"(?i)\b(curl|wget|invoke-webrequest|requests\.(get|post)|fetch\()"), "network"),
    (re.compile(r"(?i)\b(rm -rf|sudo |chmod 777|mkfs|dd if=)"), "destructive-shell"),
    (re.compile(r"(?i)(dangerously-skip-permissions|bypass ?permissions|--yolo|auto-?approve)"), "permission-bypass"),
    (re.compile(r"(?i)\b(pip|npm|pnpm|yarn|brew|apt(-get)?) (install|add)\b"), "package-install"),
    (re.compile(r"(?i)(\.env\b|api[_ ]?key|secret|token|credential)"), "secrets-mentioned"),
]
SCRIPT_SUFFIXES = (".sh", ".bash", ".py", ".js", ".mjs", ".ts", ".ps1", ".rb")
STATUS_WORDS = {"accepted": {"approved", "accepted", "decided", "final", "stable", "active", "kabul", "onaylı", "onaylandı"},
                "withdrawn": {"superseded", "deprecated", "withdrawn", "retracted", "obsolete", "replaced", "rejected"},
                "pending": {"draft", "proposed", "proposal", "pending", "wip", "provisional", "taslak"},
                "suspended": {"suspended", "paused", "on hold"}}
NEGATION = re.compile(r"(?i)\b(not|no|non|un|yet|değil|henüz)\b|\b(un|non|not)-?\w")
MUST = re.compile(r"\b(MUST|MUST NOT|SHALL|SHALL NOT|REQUIRED)\b|\b(must|must not|is required to|are required to|"
                  r"is mandatory|are mandatory|is prohibited|are prohibited|may not)\b")
SHOULD = re.compile(r"(?i)\b(should|recommend(ed|s)?|consider|best practice|guideline|tips?|prefer(ably)?|"
                    r"we suggest|you can|optional(ly)?)\b")
HISTORY = re.compile(r"(?i)(this (page|document|process|policy) (is|has been) (archived|deprecated|retired|no longer "
                     r"(maintained|in use|applies))|historical (record|document|reference)|\barchived\b|"
                     r"superseded by|no longer (applies|in effect|used|maintained))")
SCOPE = re.compile(r"(?i)\b(?:this (?:policy|process|procedure|document|page|guide|section|decision|adr) applies to|"
                   r"applies to|in scope|scope:)\s*([^\n.]{5,160})")


def status_value(status: str) -> str | None:
    """The acceptance state of an explicit status value; None when it is negated, mixed or not a known word."""
    if NEGATION.search(status):
        return None
    low = status.lower()
    words = set(re.findall(r"[^\W\d_]+", low))
    states = [state for state, vocab in STATUS_WORDS.items() if words & vocab or any(" " in v and v in low for v in vocab)]
    return states[0] if len(states) == 1 else None


def personal_ip(text: str) -> bool:
    for raw in IPV4.findall(text):
        try:
            ip = ipaddress.ip_address(raw)
        except ValueError:
            continue
        doc = any(ip in ipaddress.ip_network(n) for n in ("192.0.2.0/24", "198.51.100.0/24", "203.0.113.0/24"))
        if not (doc or ip.is_loopback or ip.is_unspecified or raw.startswith("0.") or ip.is_multicast or ip.is_private):
            return True
    return False


def front_matter(text: str) -> dict:
    m = FRONT.match(text)
    if not m:
        return {}
    out = {}
    for line in m.group(1).splitlines():  # a tolerant reader: Cursor front matter is often not valid YAML
        if ":" in line and not line.startswith((" ", "\t", "-")):
            k, v = line.split(":", 1)
            out[k.strip().lower()] = v.strip().strip("'\"")
    return out


def p(value, confidence, evidence):
    return {"value": value, "confidence": confidence, "evidence": evidence}


# --- the only input: what a real installation sees -----------------------------------------------------------
def view(case: dict, case_dir: Path, baseline: bool = False) -> dict:
    """The proposer input. Copies ONLY file bytes, path, role, declared licence and `evidence` out of the case;
    every other key (statements, why_selected, questions, group, gold) stays behind. `baseline` drops the bytes."""
    files = []
    for f in case.get("files") or []:
        text = None
        if not baseline and f.get("local_path"):
            data = (case_dir / f["local_path"]).read_bytes()
            text = None if b"\0" in data[:8192] else data.decode("utf-8", "replace")
        files.append({"path": f.get("path") or f.get("local_path") or "", "role": f.get("role") or "main",
                      "license_item": f.get("license_item"), "text": text})
    return {"id": case["id"], "files": files, "evidence": case.get("evidence") or {}}


# --- the proposer --------------------------------------------------------------------------------------------
def _login(x) -> str:
    return (x or "") if isinstance(x, str) else ""


def _is_human(login: str, user_type: str | None) -> bool:
    return bool(login) and (user_type in (None, "User")) and not BOT_LOGIN.search(login) and not MODEL_LOGIN.search(login)


def review_signals(ev: dict) -> dict:
    """Model involvement and review facts from a PR record in `evidence` (empty when the case has no PR)."""
    pr = ev.get("pr") if isinstance(ev.get("pr"), dict) else None
    if not pr:
        return {}
    author = _login(pr.get("author"))
    commits = [c for c in ev.get("commits") or [] if isinstance(c, dict)]
    model_commits = [c for c in commits
                     if GENERATOR_MODEL.search(c.get("message") or "") or MODEL_LOGIN.search(_login(c.get("author_login")))]
    model_author = bool(MODEL_LOGIN.search(author))
    reviews = [r for r in ev.get("reviews") or [] if isinstance(r, dict)]
    approvals = [r for r in reviews if r.get("state") == "APPROVED" and _is_human(_login(r.get("user")), r.get("user_type"))
                 and _login(r.get("user")) != author]
    bot_reviews = [r for r in reviews if not _is_human(_login(r.get("user")), r.get("user_type"))]
    remarks = defaultdict(list)  # human (not the PR author) -> non-trivial remarks
    for r in reviews:
        user, body = _login(r.get("user")), (r.get("body") or "").strip()
        if _is_human(user, r.get("user_type")) and user != author and len(body) >= 40 and not TRIVIAL_COMMENT.match(body):
            remarks[user].append(body)
    for c in (ev.get("review_comments") or []) + (ev.get("issue_comments") or []):
        if not isinstance(c, dict):
            continue
        user, body = _login(c.get("user")), (c.get("body") or "").strip()
        if _is_human(user, c.get("user_type")) and user != author and len(body) >= 20 and not TRIVIAL_COMMENT.match(body):
            remarks[user].append(body)
    last_model = model_commits[-1].get("sha") if model_commits else None
    shas = [c.get("sha") for c in commits]
    stale_approval = bool(approvals and last_model and last_model in shas and all(
        a.get("commit_id") in shas and shas.index(a["commit_id"]) < shas.index(last_model) for a in approvals))
    return {"model": bool(model_commits or model_author), "model_why": (
        f"{len(model_commits)} model commits" if model_commits else f"PR author {author}"),
        "approvals": approvals, "bot_reviews": bot_reviews, "remarks": dict(remarks), "stale_approval": stale_approval,
        "merged_by": _login(pr.get("merged_by"))}


def propose(v: dict) -> dict:
    out = {}
    ev = v["evidence"]
    files = v["files"]
    texts = [f["text"] for f in files if f["text"] and f["role"] != "context"]
    mains = [f for f in files if f["role"] == "main"] or files
    body = "\n".join(texts)
    main_text = "\n".join(f["text"] for f in mains if f["text"])
    fm = front_matter(mains[0]["text"]) if mains and mains[0]["text"] else {}
    rs = review_signals(ev)

    # origin and review
    tool_marker = GENERATOR_TOOL.search(body)
    model_marker = GENERATOR_MODEL.search(body)
    review_line = REVIEW.search(main_text)
    generated_by = fm.get("generated.by") or fm.get("generated_by") or fm.get("generator") or _login(ev.get("generated_by"))
    record_model = next((ev[k] for k in ("model", "engine") if isinstance(ev.get(k), str) and ev[k]), None)
    model_signal = model_marker or rs.get("model") or fm.get("extracted_from") or (
        generated_by and not generated_by.startswith("human"))
    if rs:
        humans = sorted({_login(a.get("user")) for a in rs["approvals"]} | set(rs["remarks"]))
        if rs["remarks"]:
            n = sum(len(x) for x in rs["remarks"].values())
            out["review"] = p("substantive", "low", f"{n} non-trivial remarks by {', '.join(sorted(rs['remarks']))}"
                              + ("; approval is older than the last model commit" if rs["stale_approval"] else ""))
        elif rs["approvals"]:
            out["review"] = p("approval-only", "medium" if not rs["stale_approval"] else "low",
                              f"APPROVED by {', '.join(sorted({_login(a.get('user')) for a in rs['approvals']}))}, no "
                              f"non-trivial remarks" + ("; approval is older than the last model commit"
                                                        if rs["stale_approval"] else ""))
        else:
            out["review"] = p("none", "medium", "no human approval and no human remark"
                              + (f"; bot reviews only ({len(rs['bot_reviews'])})" if rs["bot_reviews"] else "")
                              + (f"; merged by {rs['merged_by']}" if rs["merged_by"] else ""))
        if humans:
            out["reviewed_by"] = p(", ".join(humans)[:120], "low", "PR reviews/remarks by people other than the author")
    if record_model:
        out["origin"] = p("model", "high", f"evidence field model={record_model}")
    elif model_signal:  # any model involvement wins over a tool marker (docs/11 §5 input rule)
        why = (model_marker.group(0)[:60] if model_marker else rs.get("model_why") if rs.get("model")
               else f"front matter {fm.get('extracted_from') or generated_by}")
        if out.get("review", {}).get("value") == "substantive":
            out["origin"] = p("assisted", "low", f"{why}; {out['review']['evidence']} (substance not checked)")
        elif review_line and not SPELLING_ONLY.search(main_text):
            out["origin"] = p("assisted", "low", f"{why}; review line: {review_line.group(2)[:40]} (substance not checked)")
            out.setdefault("reviewed_by", p(review_line.group(2).strip()[:80], "low", "review line"))
        else:
            out["origin"] = p("model", "medium", why + ("; approval or spelling-only review is not review in substance"
                                                         if rs.get("approvals") or review_line else ""))
    elif ev.get("software_agent") or tool_marker:
        out["origin"] = p("tool", "medium", f"generator: {ev.get('software_agent') or tool_marker.group(0)[:60]}")
    elif generated_by and generated_by.startswith("human"):
        out["origin"] = p("human", "medium", f"front matter generated.by={generated_by}")
    elif main_text and len(LOG_LINE.findall(main_text)) >= 3:
        out["origin"] = p("tool", "low", "log lines (recording); the recorder is not named")
    if tool_marker and model_signal:
        out["needs_split"] = p("yes", "medium", "generator marker and model evidence in one case")

    # personal data (main content only; the PR record names its own participants by design)
    if main_text:
        hits = []
        emails = [m.group(0) for m in EMAIL.finditer(main_text) if not DOC_DOMAINS.search(m.group(0))]
        if emails:
            hits.append(f"{len(emails)} e-mail")
        if personal_ip(main_text):
            hits.append("IPv4 address")
        if PHONE.search(main_text):
            hits.append("phone number")
        if ORCID.search(main_text):
            hits.append("ORCID")
        if TCKN.search(main_text):
            hits.append("11-digit national id pattern")
        named = len(NAMED_PERSON.findall(main_text))
        if named >= 2:
            hits.append(f"{named} titled names / birth dates")
        claim = SYNTHETIC_HINT.search(main_text + "\n" + str(ev.get("source_claim") or ""))
        if hits and claim:
            out["personal_data"] = p("synthetic", "low", "; ".join(hits) + f"; '{claim.group(0)[:40]}' (issuer not trusted)")
        elif hits:
            out["personal_data"] = p("yes", "medium" if len(hits) > 1 or not named else "low", "; ".join(hits))

    # license: item-level evidence only; a collection license never replaces it (Q10)
    spdx = SPDX_HEADER.search(main_text)
    pkg_license = [f for f in files if PurePosixPath(f["path"]).name.upper() in ("LICENSE", "LICENSE.TXT", "LICENSE.MD")]
    declared = next((f["license_item"] for f in mains if f["license_item"]), None)
    if fm.get("license"):
        out["license"] = p(fm["license"], "medium", "front matter license")
    elif spdx:
        out["license"] = p(spdx.group(1), "high", "SPDX header")
    elif pkg_license:
        out["license"] = p("see package LICENSE", "medium", f"license file in the package: {pkg_license[0]['path']}")
    elif declared and declared != "unknown":
        out["license"] = p(declared, "medium", "declared item license")
    else:
        out["license"] = p("unknown", "medium", "no item-level license")

    # ai_use: only what the item states; absent stays absent (D60)
    cu, tdm = CONTENT_USAGE.search(main_text), TDM.search(main_text)
    if cu:
        terms = dict(t.strip().split("=", 1) for t in cu.group(1).split(",") if "=" in t)
        mapped = {"train": terms.get("train-ai"), "ai_input": terms.get("ai-use"), "search": terms.get("search")}
        out["ai_use"] = p({k: v for k, v in mapped.items() if v in ("y", "n")}, "medium", f"Content-Usage: {cu.group(1)[:60]}")
    elif tdm and tdm.group(1) == "1":
        out["ai_use"] = p({"train": "n"}, "low", "tdm-reservation=1 (training reserved)")

    # acceptance: only a status line the case shows (in a file, or as raw evidence); a retraction or supersession
    # by another key is only a contest mark. Statements and reference answers are never read.
    ev_status = next((ev[k] for k in ("status_line", "status") if isinstance(ev.get(k), str) and ev[k].strip()), None)
    m = STATUS.search(main_text)
    status = fm.get("status") or (m.group(1) if m else None) or ev_status
    acts = [a for a in (ev.get("retracted_by") or []) + (ev.get("superseded_by_records") or []) if isinstance(a, dict)]
    if any(a.get("same_key") for a in acts):
        out["acceptance"] = p("withdrawn", "medium", "retracted/superseded by the same key")
    else:
        if acts:
            out["contest"] = p("yes", "medium", "retraction or supersession by another key only: a contest mark")
        state = status_value(status) if status else None
        if state:
            out["acceptance"] = p(state, "low", f"status line: {status.strip()[:30]}")

    # time and scope. `stale_after` is a freshness deadline, never the end of validity (docs/20 §5, Q15).
    if fm.get("valid_to") or fm.get("valid_until"):
        out["valid_to"] = p(fm.get("valid_to") or fm.get("valid_until"), "medium", "front matter")
    if fm.get("stale_after"):
        out["stale_after"] = p(fm["stale_after"], "medium", "front matter stale_after (review date, not validity)")
    date = DATE_IN_NAME.search(mains[0]["path"] if mains else "")
    if date:
        out["issued"] = p(date.group(1), "low", "date in the file name")
    scope = fm.get("applyto") or fm.get("globs") or fm.get("paths") or fm.get("platform")
    sm = SCOPE.search(main_text)
    if scope:
        out["applies_to"] = p(scope, "medium", "front matter scope")
    if scope or sm:
        out["scope"] = p((scope or sm.group(1)).strip()[:160], "low", "front matter scope" if scope else "scope sentence")

    # normative meaning: binding rule, advice or history (a weak lexical signal; a person decides)
    if main_text and not rs:
        musts, shoulds = len(MUST.findall(main_text)), len(SHOULD.findall(main_text))
        hist = HISTORY.search(main_text)
        withdrawn = bool(status) and status_value(status) == "withdrawn"
        if hist or withdrawn:
            out["normative"] = p("history", "low", f"history marker: {(hist.group(0) if hist else status)[:40]}")
        elif musts >= 3 and musts >= shoulds:
            out["normative"] = p("binding", "low", f"{musts} must/shall vs {shoulds} should/recommend")
        elif shoulds >= 3:
            out["normative"] = p("advice", "low", f"{shoulds} should/recommend vs {musts} must/shall")

    # agent instructions and activation risk (a whole package is one case)
    names = [PurePosixPath(f["path"]).name for f in files]
    skills = agentfiles.skill_dirs(f["path"] for f in files)
    instruction = any(agentfiles.is_instruction({"path": f["path"], "okf_type": fm.get("type") if f is mains[0] else None},
                                                skills) for f in files if f["role"] != "diff")
    instruction = instruction or (fm.get("type") or "").lower() in agentfiles.INSTRUCTION_TYPES
    hostile = sorted({label for rx, label in HOSTILE for t in texts if rx.search(t)})
    if instruction or hostile:
        out["instruction"] = p("yes" if instruction else "no", "medium", "file name / skill or agent folder / front matter")
    if hostile:
        out["activate"] = p("deny", "high", "hostile patterns: " + ", ".join(hostile))
        out["activation_risk"] = p("harmful", "medium", "hostile patterns: " + ", ".join(hostile))
    elif instruction:
        risky = sorted({label for rx, label in RISKY for t in texts if rx.search(t)})
        scripts = [n for n in names if n.endswith(SCRIPT_SUFFIXES)]
        if scripts:
            risky.append(f"{len(scripts)} script files")
        if risky:
            out["activation_risk"] = p("risky", "low", "powers: " + ", ".join(risky))
        elif texts:
            out["activation_risk"] = p("safe", "low", "instruction text with no hostile pattern and no listed power")
    return out


# --- run and evaluate ----------------------------------------------------------------------------------------
def load(root: Path, set_name: str, slice_name: str | None):
    """(case, case_dir) for each line of <root>/<set>/<slice>.cases.jsonl (or <slice>.<part>.cases.jsonl); the case
    folder is <root>/<set>/<slice>/<case id>."""
    base = root / set_name
    indexes = sorted(base.glob(f"{slice_name}.cases.jsonl")) + sorted(base.glob(f"{slice_name}.*.cases.jsonl")) \
        if slice_name else sorted(base.glob("*.cases.jsonl"))
    for index in indexes:
        slice_dir = base / index.name.split(".", 1)[0]
        for line in index.read_text().splitlines():
            if line.strip():
                case = json.loads(line)
                yield case, slice_dir / case["id"]


def run(root: Path, set_name: str, slice_name: str | None, baseline: bool) -> list[dict]:
    version = BASELINE_VERSION if baseline else RULES_VERSION
    return [{"id": case["id"], "set": set_name, "group": case.get("group"), "proposer_version": version,
             "mode": "baseline" if baseline else "rules", "proposals": propose(view(case, case_dir, baseline))}
            for case, case_dir in load(root, set_name, slice_name)]


def evaluate(root: Path, set_name: str, rows: list[dict]):
    """Agreement with the gold answers of the set (<root>/<set>/*.gold.jsonl). Read only here, after proposing."""
    gold = {}
    for f in sorted((root / set_name).glob("*.gold.jsonl")):
        for line in f.read_text().splitlines():
            if line.strip():
                g = json.loads(line)
                gold[g["id"]] = g.get("gold") or {}
    table = defaultdict(Counter)
    for r in rows:
        for field, fact in gold.get(r["id"], {}).items():
            if not isinstance(fact, str):
                continue
            got = r["proposals"].get(field, {}).get("value")
            table[field]["n"] += 1
            table[field]["agree" if got == fact else ("missing" if got is None else "wrong")] += 1
    print("\n| field | n | agree | wrong | missing |\n|---|---|---|---|---|")
    for f, c in sorted(table.items()):
        print(f"| {f} | {c['n']} | {c['agree']} | {c['wrong']} | {c['missing']} |")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--set", required=True, choices=("auto", "scenario", "human"))
    ap.add_argument("--slice")
    ap.add_argument("--baseline", action="store_true", help="metadata only: path, licence and evidence, no file bytes")
    ap.add_argument("--out")
    ap.add_argument("--eval", action="store_true")
    args = ap.parse_args()
    root = Path(args.root)
    rows = run(root, args.set, args.slice, args.baseline)
    out = Path(args.out) if args.out else root / f"proposals{'_baseline' if args.baseline else ''}.{args.set}.jsonl"
    out.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    cover = Counter(f for r in rows for f in r["proposals"])
    print(f"{len(rows)} cases → {out}; proposals per field: {dict(cover.most_common())}")
    if args.eval:
        evaluate(root, args.set, rows)
    return 0


if __name__ == "__main__":
    sys.exit(main())

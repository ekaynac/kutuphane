"""Labelling v5 rule proposer (docs/20 §5, D67). It suggests labels for one whole case (a document, a skill package,
a PR with its review record) from what a real installation sees, and from nothing else.

Its only input is `view(case)`: for each file the bytes (as text), the path, the role and the declared item licence,
plus the case's raw `evidence`. It never reads `statements`, `why_selected`, `questions`, the group, or any
`*.gold.jsonl` / reference file: those hold answers under test (Astra P0, the v4 `known.acceptance` leak).

Each proposal: {"value", "confidence": high|medium|low, "evidence"}. A field with no signal is not proposed.
`--baseline` is the metadata-only baseline: the same rules without the file bytes (path, licence and evidence only).

    python propose.py <root> --set human [--slice pool] [--baseline] [--out FILE] [--eval]
        # reads <root>/<set>/<slice>.cases.jsonl (all slices when --slice is absent) and the case folders
        # writes <root>/proposals.<set>.jsonl, or <root>/proposals_baseline.<set>.jsonl with --baseline
"""

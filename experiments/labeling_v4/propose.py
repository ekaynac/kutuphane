"""Labelling v4 rule proposer (G6, docs/16 §4). It suggests labels from signals that a real installation has:
the file bytes, its path, the declared item license, git signals (co-author trailers, commit authors) and
record fields. It never reads the evaluation facts in `known` of the synthetic stratum (S).

Each proposal: {"value", "confidence": high|medium|low, "evidence"}. A field with no signal is not proposed.
Origin values follow kstd plus the candidate `tool` (docs/17, not decided yet).

    python propose.py <dataset dir>            # writes <dataset dir>/proposals.jsonl
    python propose.py <dataset dir> --eval     # also scores proposals against the stated facts
"""
import argparse
import ipaddress
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))
from kutuphane import agentfiles  # noqa: E402  (instruction-file rules of Kütüphane itself)

# --- signals -----------------------------------------------------------------------------------------------
GENERATOR_TOOL = re.compile(  # a NAMED rule-based generator only; generic "this file was generated" proves nothing
    r"(?i)(generated by (typedoc|schemadoc|tools/[\w-]+|sphinx|doxygen|openapi[- ]generator|protoc[\w-]*|buf|"
    r"swagger-codegen|sqlc|jooq|graphql-codegen)|code generated by [\w./-]+.{0,40}do not edit)")
GENERATOR_MODEL = re.compile(
    r"(?i)(generated with \[?claude code|🤖 generated with|co-authored-by: (claude|copilot|codex|gpt|gemini)|"
    r"(generated|written|drafted|created) (by|with) (an? )?(ai|llm|claude|chatgpt|gpt-?\d|gemini|copilot|"
    r"language model)|hazırlayan: claude|automatically extracted via (local )?llm|llm-assisted)")
REVIEW = re.compile(r"(?im)^\s*(reviewed[- ]by|approved[- ]by|reviewer|onaylayan)\s*[:=]\s*(.+)$")
SPELLING_ONLY = re.compile(r"(?i)(spelling|typo|grammar|formatting)[- ]only|only (fixed )?(spelling|typos|grammar)")
LOG_LINE = re.compile(r"(?m)^(\d{4}-\d\d-\d\d[T ]\d\d:\d\d:\d\d|\w{3} [ \d]\d \d\d:\d\d:\d\d|\S+ - - \[\d\d/\w{3}/\d{4})")
EMAIL = re.compile(r"\b[\w.+-]+@([\w-]+\.)+[a-z]{2,}\b", re.I)
IPV4 = re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b")
PHONE = re.compile(r"(?<!\w)\+\d{1,3}[ \-]?\(?\d{1,4}\)?([ \-]?\d{2,4}){2,4}(?!\w)")
ORCID = re.compile(r"orcid\.org/\d{4}-\d{4}-\d{4}-\d{3}[\dX]")
TCKN = re.compile(r"(?<!\d)[1-9]\d{10}(?!\d)")
SYNTHETIC_HINT = re.compile(r"(?i)\b(synthetic|fake|dummy|fictitious|made-up|invented)\b.{0,40}\b(data|record|person|customer|name)")
DOC_DOMAINS = re.compile(r"(?i)@(example\.(com|org|net)|[\w.-]+\.(invalid|test|example)|users\.noreply\.github\.com)$")
SPDX_HEADER = re.compile(r"SPDX-License-Identifier:\s*([^\s*]+(?:\s+(?:AND|OR|WITH)\s+[^\s*]+)*)")
CONTENT_USAGE = re.compile(r"(?i)content-usage\s*[:=]\s*\"?([^\"\n>]+)")
TDM = re.compile(r"(?i)tdm-reservation\"?\s*[:=]\s*\"?([01])")
STATUS = re.compile(r"(?im)^\s*(?:\*\*)?status(?:\*\*)?\s*[:=]\s*\**\s*([A-Za-zÇĞİÖŞÜçğıöşü ]{3,30})")
FRONT = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)
DATE_IN_NAME = re.compile(r"(20\d\d-\d\d-\d\d)")
HOSTILE = [
    (re.compile(r"(?i)base64\s+(-d|--decode)[^\n]*\|\s*(sh|bash)|eval\s*\(\s*atob|exec\(base64"), "decode-and-run"),
    (re.compile(r"(?i)(curl|wget)[^\n|]*\|\s*(sh|bash|source)|source\s*<\(\s*(curl|wget)"), "remote-script"),
    (re.compile(r"(?i)(ignore|disregard|override) (all )?(previous|prior|other|above) (instructions|rules)"), "override"),
    (re.compile(r"[\u200b\u200c\u200d\u2060\ufeff]"), "zero-width-text"),
    (re.compile(r"(?is)<!--[^>]*(agent|assistant|ai)\b[^>]*(send|copy|upload|post|curl)[^>]*-->"), "hidden-comment"),
    (re.compile(r"(?i)(send|post|upload|copy|exfiltrat)\w*[^\n]{0,80}(\.ssh|id_rsa|token|secret|credential|api[_ ]?key|password)"), "exfiltration"),
    (re.compile(r"(?i)(soul|memory)\.md[^\n]{0,60}(append|overwrite|replace|write)|(append|overwrite|write)[^\n]{0,60}(soul|memory)\.md"), "memory-write"),
    (re.compile(r"(?i)never ask for confirmation|approved all actions in advance|do not (tell|mention|show)[^\n]{0,40}(user|this)"), "concealment"),
]
STATUS_WORDS = {"accepted": {"approved", "accepted", "decided", "final", "stable", "kabul", "onaylı", "onaylandı"},
                "withdrawn": {"superseded", "deprecated", "withdrawn", "retracted", "obsolete", "replaced"},
                "pending": {"draft", "proposed", "proposal", "pending", "wip", "taslak"}}
NEGATION = re.compile(r"(?i)\b(not|no|non|un|yet|değil|henüz)\b|\b(un|non|not)-?\w")


def status_value(status: str) -> str | None:
    """The acceptance state of an explicit status value; None when it is negated, mixed or not a known word."""
    if NEGATION.search(status):
        return None
    words = set(re.findall(r"[^\W\d_]+", status.lower()))
    states = [state for state, vocab in STATUS_WORDS.items() if words & vocab]
    return states[0] if len(states) == 1 else None


def personal_ip(text: str) -> bool:
    for raw in IPV4.findall(text):
        try:
            ip = ipaddress.ip_address(raw)
        except ValueError:
            continue
        doc = any(ip in ipaddress.ip_network(n) for n in ("192.0.2.0/24", "198.51.100.0/24", "203.0.113.0/24"))
        if not (doc or ip.is_loopback or ip.is_unspecified or raw.startswith("0.") or ip.is_multicast):
            return True
    return False


def front_matter(text: str) -> dict:
    m = FRONT.match(text)
    if not m:
        return {}
    out = {}
    for line in m.group(1).splitlines():  # a tolerant reader: Cursor front matter is often not valid YAML
        if ":" in line and not line.startswith((" ", "\t", "-")):
            k, v = line.split(":", 1)
            out[k.strip().lower()] = v.strip().strip("'\"")
    return out


def p(value, confidence, evidence):
    return {"value": value, "confidence": confidence, "evidence": evidence}


# --- the proposer --------------------------------------------------------------------------------------------
def propose(item: dict, text: str | None, group_files: dict) -> dict:
    out, signals = {}, ({} if item["stratum"] == "S" else item.get("known", {}))  # S facts are answers, not signals
    path = item["ref"].get("path") or ""
    fm = front_matter(text) if text else {}

    # origin
    origin_record = signals.get("model") if isinstance(signals.get("model"), str) else None
    tool_marker = GENERATOR_TOOL.search(text or "")
    model_marker = GENERATOR_MODEL.search(text or "")
    co_authored = signals.get("commits_with_co_author") or 0
    review = REVIEW.search(text or "")
    generated_by = fm.get("generated.by") or fm.get("generated_by") or fm.get("generator")
    model_signal = model_marker or co_authored or fm.get("extracted_from") or (generated_by and not generated_by.startswith("human"))
    if origin_record or signals.get("engine"):
        out["origin"] = p("model", "high", f"record field model={origin_record or signals.get('engine')}")
    elif model_signal:  # any model involvement wins over a tool marker (docs/11 §5 input rule)
        why = model_marker.group(0)[:60] if model_marker else (f"{co_authored} co-authored commits" if co_authored
                                                                 else f"front matter {fm.get('extracted_from') or generated_by}")
        if review and not SPELLING_ONLY.search(text or ""):
            out["origin"] = p("assisted", "low", f"{why}; review line: {review.group(2)[:40]} (substance not checked)")
            out["reviewed_by"] = p(review.group(2).strip()[:80], "low", "review line")
        else:
            out["origin"] = p("model", "medium", why + ("; review is spelling-only" if review else ""))
    elif signals.get("software_agent") or signals.get("generator_marker") or tool_marker:
        out["origin"] = p("tool", "medium", f"generator: {signals.get('software_agent') or signals.get('generator_marker') or tool_marker.group(0)[:60]}")
    elif generated_by and generated_by.startswith("human"):
        out["origin"] = p("human", "medium", f"front matter generated.by={generated_by}")
    elif text and len(LOG_LINE.findall(text)) >= 3:
        out["origin"] = p("tool", "low", "log lines (recording); the recorder is not named")
    if tool_marker and model_signal:
        out["needs_split"] = p("yes", "medium", "generator marker and model evidence in one file")

    # personal data
    if text is not None:
        hits = []
        emails = [m.group(0) for m in EMAIL.finditer(text) if not DOC_DOMAINS.search(m.group(0))]
        if emails:
            hits.append(f"{len(emails)} e-mail")
        if personal_ip(text):
            hits.append("IPv4 address")
        if PHONE.search(text):
            hits.append("phone number")
        if ORCID.search(text):
            hits.append("ORCID")
        if TCKN.search(text):
            hits.append("11-digit national id pattern")
        if hits and SYNTHETIC_HINT.search(text):
            out["personal_data"] = p("synthetic", "low", "; ".join(hits) + "; text calls the data synthetic (not trusted)")
        elif hits:
            out["personal_data"] = p("yes", "medium", "; ".join(hits))

    # license: item-level evidence only; a collection license never replaces it (Q10)
    spdx = SPDX_HEADER.search(text or "")
    if fm.get("license"):
        out["license"] = p(fm["license"], "medium", "front matter license")
    elif spdx:
        out["license"] = p(spdx.group(1), "high", "SPDX header")
    elif group_files.get("LICENSE.txt") or group_files.get("LICENSE"):
        out["license"] = p("see group LICENSE", "medium", "license file in the skill folder")
    elif item.get("license_item") and item["license_item"] != "unknown":
        out["license"] = p(item["license_item"], "medium", "declared item license")
    else:
        out["license"] = p("unknown", "medium", "no item-level license"
                           + (f" (collection: {item.get('license_collection')})" if item.get("license_collection") else ""))

    # ai_use: only what the item states; absent stays absent (D60)
    cu, tdm = CONTENT_USAGE.search(text or ""), TDM.search(text or "")
    if cu:
        terms = dict(t.strip().split("=", 1) for t in cu.group(1).split(",") if "=" in t)
        mapped = {"train": terms.get("train-ai"), "ai_input": terms.get("ai-use"), "search": terms.get("search")}
        out["ai_use"] = p({k: v for k, v in mapped.items() if v in ("y", "n")}, "medium", f"Content-Usage: {cu.group(1)[:60]}")
    elif tdm and tdm.group(1) == "1":
        out["ai_use"] = p({"train": "n"}, "low", "tdm-reservation=1 (training reserved)")

    # acceptance: the item's own declared state; a retraction by another key is only a contest mark
    status = fm.get("status") or (STATUS.search(text or "").group(1) if STATUS.search(text or "") else None)
    known_acc = signals.get("acceptance") if isinstance(signals.get("acceptance"), str) else None
    acts = (signals.get("retracted_by") or []) + (signals.get("superseded_by") or [])
    if any(r.get("same_key") for r in acts):
        out["acceptance"] = p("withdrawn", "medium", "retracted/superseded by the same key")
    else:
        if acts:
            out["contest"] = p("yes", "medium", "retraction or supersession by another key only: a contest mark")
        state = status_value(status) if status else None
        if state:
            out["acceptance"] = p(state, "low", f"status line: {status.strip()[:30]}")
        elif known_acc and not known_acc.startswith("src:"):
            out["acceptance"] = p(known_acc, "medium", "source state")

    # validity time and scope
    if fm.get("stale_after") or fm.get("valid_to"):
        out["valid_to"] = p(fm.get("valid_to") or fm.get("stale_after"), "medium", "front matter")
    date = DATE_IN_NAME.search(path)
    if date:
        out["issued"] = p(date.group(1), "low", "date in the file name")
    scope = fm.get("applyto") or fm.get("globs") or fm.get("paths") or fm.get("platform")
    if scope:
        out["applies_to"] = p(scope, "medium", "front matter scope")

    # agent instructions and hostile text (activate)
    name = path.rsplit("/", 1)[-1]
    instruction = agentfiles.instruction_name(name) or (fm.get("type") or "").lower() in agentfiles.INSTRUCTION_TYPES \
        or bool(item.get("group")) or name.endswith(agentfiles.INSTRUCTION_SUFFIXES)
    hostile = [label for rx, label in HOSTILE if rx.search(text or "")]
    if instruction or hostile:
        out["instruction"] = p("yes" if instruction else "no", "medium", "file name / skill folder / front matter")
    if hostile:
        out["activate"] = p("deny", "high", "hostile patterns: " + ", ".join(hostile))
    return out


# --- run and evaluate ----------------------------------------------------------------------------------------
def load(root: Path):
    for f in sorted((root / "items").glob("*.jsonl")):
        for line in f.read_text().splitlines():
            if line.strip():
                yield json.loads(line)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--eval", action="store_true")
    args = ap.parse_args()
    root = Path(args.root)
    items = list(load(root))
    groups = defaultdict(dict)
    for it in items:
        if it.get("group") and it.get("local_path"):
            groups[it["group"]][Path(it["local_path"]).name] = it["id"]
    rows = []
    for it in items:
        text = None
        if it.get("local_path"):
            data = (root / it["local_path"]).read_bytes()
            text = None if b"\0" in data[:8192] else data.decode("utf-8", "replace")
        rows.append({"id": it["id"], "stratum": it["stratum"], "proposals": propose(it, text, groups.get(it.get("group"), {}))})
    (root / "proposals.jsonl").write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    cover = Counter(f for r in rows for f in r["proposals"])
    print(f"{len(rows)} items; proposals per field: {dict(cover.most_common())}")
    if args.eval:
        evaluate(items, {r["id"]: r["proposals"] for r in rows})
    return 0


def norm(field, value):
    if not isinstance(value, str):
        return value
    v = value.removeprefix("src:")
    if field == "origin" and v in ("program", "classifier", "captured-api-response"):
        return {"program": "tool", "captured-api-response": "tool", "classifier": "model"}[v]
    if field == "acceptance" and v == "superseded":
        return "withdrawn"
    return v


def evaluate(items, proposals):
    """Agreement of proposals with stated facts. For S the facts are expected labels; for R/W/A they are what the
    source states (a dataset label, a record field). Missing = the proposer gave no value."""
    table = defaultdict(lambda: Counter())
    for it in items:
        for field in ("origin", "personal_data", "acceptance", "needs_split"):
            fact = norm(field, it.get("known", {}).get(field))
            if fact is None or (isinstance(fact, str) and " " in fact):
                continue
            got = proposals[it["id"]].get(field, {}).get("value")
            key = (it["stratum"], field)
            table[key]["n"] += 1
            table[key]["agree" if got == fact else ("missing" if got is None else "wrong")] += 1
    hostile = [(it["stratum"], bool(it.get("hostile")), proposals[it["id"]].get("activate", {}).get("value") == "deny")
               for it in items if it["stratum"] in ("A", "S")]
    print("\n| stratum | field | n | agree | wrong | missing |\n|---|---|---|---|---|---|")
    for (s, f), c in sorted(table.items()):
        print(f"| {s} | {f} | {c['n']} | {c['agree']} | {c['wrong']} | {c['missing']} |")
    tp = sum(1 for _, h, d in hostile if h and d)
    fn = sum(1 for _, h, d in hostile if h and not d)
    fp = sum(1 for _, h, d in hostile if not h and d)
    print(f"\nhostile → activate deny: caught {tp}, missed {fn}, false alarms {fp} (A + S)")


if __name__ == "__main__":
    sys.exit(main())
